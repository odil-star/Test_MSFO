function parseQuestions(text) {

  const blocks = text
    .split('++++++')
    .map(item => item.trim())
    .filter(Boolean);

  const questions = [];

  blocks.forEach(block => {

    const lines = block
      .split('\n')
      .map(line => line.trim())
      .filter(Boolean);

    const question = lines[0];

    const answers = [];

    let correctAnswer = "";

    lines.forEach(line => {

      if (line.startsWith('#')) {

        const answer =
          line.replace('#', '').trim();

        correctAnswer = answer;

        answers.push(answer);

      } else if (
        line !== '=======' &&
        line !== '=====' &&
        line !== '==========' &&
        line !== '============'
      ) {

        if (line !== question) {
          answers.push(line);
        }

      }

    });

    const shuffledAnswers = [...answers].sort(
      () => Math.random() - 0.5
    );

    const correct =
      shuffledAnswers.indexOf(correctAnswer);

    questions.push({
      question,
      answers: shuffledAnswers,
      correct
    });

  });

  return questions;
}


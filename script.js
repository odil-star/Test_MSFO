async function showLeaders() {
  const leaders = document.getElementById("leaders");

  if (!leaders) return;

  const q = query(
    collection(db, "results"),
    orderBy("score", "desc"),
    limit(10)
  );

  const querySnapshot = await getDocs(q);

  leaders.innerHTML = "";

  let place = 1;

  querySnapshot.forEach((doc) => {
    const data = doc.data();

    leaders.innerHTML += `
      <div class="leader">
        <span>${place}. ${data.name}</span>
        <b>${data.score}/25</b>
      </div>
    `;

    place++;
  });
}

